var menuIcons = map[*ui.SVG]*mygo.MenuIcon{}

// Menu makes a menu icon of an icon once, as menus need; call it on the
// main thread.
func Menu(s *ui.SVG) ui.MenuIcon {
	i, ok := menuIcons[s]
	if !ok {
		i, _ = mygo.NewMenuIconSVG(s, true)
		menuIcons[s] = i
	}
	if i == nil {
		return nil
	}
	return i
}
